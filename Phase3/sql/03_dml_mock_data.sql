SELECT
    table_name,
    row_count
FROM (
    SELECT 'warehouse' AS table_name, COUNT(*) AS row_count, 1 AS ord FROM warehouse
    UNION ALL SELECT 'supplier', COUNT(*), 2 FROM supplier
    UNION ALL SELECT 'product', COUNT(*), 3 FROM product
    UNION ALL SELECT 'customer', COUNT(*), 4 FROM customer
    UNION ALL SELECT 'product_component', COUNT(*), 5 FROM product_component
    UNION ALL SELECT 'inventory', COUNT(*), 6 FROM inventory
    UNION ALL SELECT 'supplier_product', COUNT(*), 7 FROM supplier_product
    UNION ALL SELECT 'purchase_order', COUNT(*), 8 FROM purchase_order
    UNION ALL SELECT 'po_line', COUNT(*), 9 FROM po_line
    UNION ALL SELECT 'shipment', COUNT(*), 10 FROM shipment
    UNION ALL SELECT 'warehouse_transfer', COUNT(*), 11 FROM warehouse_transfer
    UNION ALL SELECT 'customer_delivery', COUNT(*), 12 FROM customer_delivery
    UNION ALL SELECT 'shipment_line', COUNT(*), 13 FROM shipment_line
    UNION ALL SELECT 'goods_receipt', COUNT(*), 14 FROM goods_receipt
    UNION ALL SELECT 'TOTAL_ALL_14_TABLES',
        (SELECT COUNT(*) FROM warehouse) + (SELECT COUNT(*) FROM supplier) +
        (SELECT COUNT(*) FROM product) + (SELECT COUNT(*) FROM customer) +
        (SELECT COUNT(*) FROM product_component) + (SELECT COUNT(*) FROM inventory) +
        (SELECT COUNT(*) FROM supplier_product) + (SELECT COUNT(*) FROM purchase_order) +
        (SELECT COUNT(*) FROM po_line) + (SELECT COUNT(*) FROM shipment) +
        (SELECT COUNT(*) FROM warehouse_transfer) + (SELECT COUNT(*) FROM customer_delivery) +
        (SELECT COUNT(*) FROM shipment_line) + (SELECT COUNT(*) FROM goods_receipt), 15
) AS summary_stats
ORDER BY ord ASC;
